export function translate(language: Language, key: TranslationKey) {
  return dictionaries[language][key] ?? dictionaries.en[key];
}

export function localName(name: LocalizedName, language: Language) {
  return name[language] || name.en || name.ar;
}

export function directionFor(language: Language) {
  return language === "ar" ? "rtl" : "ltr";
}
